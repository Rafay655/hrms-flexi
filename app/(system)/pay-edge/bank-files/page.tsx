"use client";

import { showApiError } from "@/lib/error-toast";
import React, { useState, useMemo } from "react";
import { useQuery } from "@tanstack/react-query";
import toast from "react-hot-toast";
import {
  Eye,
  Download,
  MoreVertical,
  Search,
  ChevronLeft,
  ChevronRight,
  ChevronsLeft,
  ChevronsRight,
  Loader2,
  FileText,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Badge } from "@/components/ui/badge";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { useBankFilesList, useBankFileDetail } from "@/hooks/useBankFiles";
import { downloadBankFile } from "@/services/bank-files";
import type { BankFile } from "@/types/bank-file";

/* ----------------------------------------------------------------------- */
/* Helpers                                                                  */
/* ----------------------------------------------------------------------- */

function StatusBadge({ status }: { status: string }) {
  const map: Record<string, string> = {
    generated: "border-blue-200 bg-blue-50 text-blue-700",
    downloaded: "border-green-200 bg-green-50 text-green-700",
    uploaded: "border-purple-200 bg-purple-50 text-purple-700",
  };
  return (
    <Badge variant="outline" className={`text-xs capitalize ${map[status] ?? "border-gray-200"}`}>
      {status}
    </Badge>
  );
}

function formatPKR(value: string) {
  const num = parseFloat(value);
  return isNaN(num) ? "—" : `PKR ${num.toLocaleString()}`;
}

/* ----------------------------------------------------------------------- */
/* Main Page Component                                                      */
/* ----------------------------------------------------------------------- */

export default function BankFilesPage() {
  const [page, setPage] = useState(1);
  const [perPage, setPerPage] = useState(10);
  const [search, setSearch] = useState("");
  const [detailId, setDetailId] = useState<string | null>(null);

  const { data, isLoading, isFetching } = useBankFilesList(page, perPage);
  const files: BankFile[] = data?.data ?? [];
  const totalEntries = data?.meta?.total ?? 0;
  const totalPages = data?.meta?.last_page ?? 1;

  const { data: detailData, isLoading: isLoadingDetail } = useBankFileDetail(detailId);

  const handleView = (file: BankFile) => {
    setDetailId(file.id);
  };

  const handleDownload = async (file: BankFile) => {
    try {
      const blob = await downloadBankFile(file.id);
      const url = window.URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = url;
      link.download = file.filename;
      document.body.appendChild(link);
      link.click();
      link.remove();
      window.URL.revokeObjectURL(url);
      toast.success("Download started.");
    } catch (err: any) {
      showApiError(err, { fallbackMessage: err?.response?.data?.message ?? "Download failed." });
    }
  };

  // Client‑side search
  const filteredFiles = useMemo(() => {
    if (!search.trim()) return files;
    const q = search.toLowerCase();
    return files.filter(
      (f) =>
        f.filename.toLowerCase().includes(q) ||
        f.generated_by.toLowerCase().includes(q) ||
        f.status.toLowerCase().includes(q)
    );
  }, [files, search]);

  const showingFrom = totalEntries > 0 ? (page - 1) * perPage + 1 : 0;
  const showingTo = totalEntries > 0 ? Math.min(page * perPage, totalEntries) : 0;

  return (
    <div className="p-3">
      <Card className="border border-gray-100 shadow-sm">
        <CardHeader className="border-b">
          <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
            <div>
              <CardTitle className="text-2xl font-bold text-gray-900">
                Bank Files
              </CardTitle>
              <p className="text-sm text-gray-500 mt-1">
                {totalEntries.toLocaleString()} files · Generated bank disbursement files
              </p>
            </div>
          </div>
        </CardHeader>

        <CardContent className="p-6">
          {/* Filters */}
          <div className="flex flex-col md:flex-row gap-4 mb-6">
            <div className="relative flex-1">
              <Search className="absolute left-3 top-3 h-4 w-4 text-gray-400" />
              <Input
                placeholder="Search by filename, generated by, or status..."
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                className="pl-10 border-gray-300"
              />
            </div>
            <div className="flex items-center gap-2">
              <span className="text-sm text-gray-600">Show</span>
              <Select
                value={perPage.toString()}
                onValueChange={(v) => {
                  setPerPage(Number(v));
                  setPage(1);
                }}
              >
                <SelectTrigger className="w-full border-gray-300">
                  <SelectValue placeholder="10" />
                </SelectTrigger>
                <SelectContent>
                  {[10, 25, 50, 100].map((size) => (
                    <SelectItem key={size} value={size.toString()}>
                      {size}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
              <span className="text-sm text-gray-600">entries</span>
            </div>
          </div>

          {/* Stats Bar */}
          <div className="bg-blue-50 border border-blue-100 rounded-lg p-4 mb-4 flex items-center justify-between">
            <div className="text-sm">
              <span className="text-gray-600">Showing</span>
              <span className="font-semibold mx-1">{showingFrom}</span>
              <span className="text-gray-600">to</span>
              <span className="font-semibold mx-1">{showingTo}</span>
              <span className="text-gray-600">of</span>
              <span className="font-semibold mx-1">{totalEntries}</span>
              <span className="text-gray-600">entries</span>
            </div>
            {(isLoading || isFetching) && (
              <Badge className="ml-2">
                <Loader2 className="h-3 w-3 animate-spin" />
              </Badge>
            )}
          </div>

          {/* Table */}
          <div className="border border-gray-200 rounded-lg overflow-hidden">
            <div className="overflow-x-auto">
              <table className="w-full">
                <thead className="bg-gray-50 border-b border-gray-200">
                  <tr>
                    <th className="py-3 px-6 text-left text-xs font-semibold text-gray-700 uppercase tracking-wider w-12">SR.</th>
                    <th className="py-3 px-6 text-left text-xs font-semibold text-gray-700 uppercase tracking-wider">Filename</th>
                    <th className="py-3 px-6 text-right text-xs font-semibold text-gray-700 uppercase tracking-wider">Total Amount</th>
                    <th className="py-3 px-6 text-center text-xs font-semibold text-gray-700 uppercase tracking-wider">Transactions</th>
                    <th className="py-3 px-6 text-left text-xs font-semibold text-gray-700 uppercase tracking-wider">Status</th>
                    <th className="py-3 px-6 text-left text-xs font-semibold text-gray-700 uppercase tracking-wider">Generated By</th>
                    <th className="py-3 px-6 text-center text-xs font-semibold text-gray-700 uppercase tracking-wider">Actions</th>
                  </tr>
                </thead>
                <tbody className="bg-white divide-y divide-gray-100">
                  {isLoading ? (
                    <tr>
                      <td colSpan={7} className="py-12 text-center">
                        <Loader2 className="h-6 w-6 animate-spin mx-auto text-gray-400" />
                      </td>
                    </tr>
                  ) : filteredFiles.length === 0 ? (
                    <tr>
                      <td colSpan={7} className="py-12 text-center text-gray-500">
                        <FileText className="mx-auto mb-2 h-6 w-6 text-gray-300" />
                        No bank files found.
                      </td>
                    </tr>
                  ) : (
                    filteredFiles.map((file, idx) => (
                      <tr key={file.id} className="hover:bg-gray-50">
                        <td className="py-4 px-6 text-sm text-gray-500">{showingFrom + idx}</td>
                        <td className="py-4 px-6 text-sm font-medium text-gray-900">{file.filename}</td>
                        <td className="py-4 px-6 text-sm text-right font-mono tabular-nums">{formatPKR(file.total_amount)}</td>
                        <td className="py-4 px-6 text-sm text-center">{file.transaction_count}</td>
                        <td className="py-4 px-6"><StatusBadge status={file.status} /></td>
                        <td className="py-4 px-6 text-sm text-gray-700">{file.generated_by}</td>
                        <td className="py-4 px-6 text-center">
                          <DropdownMenu>
                            <DropdownMenuTrigger asChild>
                              <Button variant="ghost" size="icon" className="h-8 w-8">
                                <MoreVertical className="h-4 w-4" />
                              </Button>
                            </DropdownMenuTrigger>
                            <DropdownMenuContent align="end">
                              <DropdownMenuItem onClick={() => handleView(file)}>
                                <Eye className="mr-2 h-3.5 w-3.5" /> View Details
                              </DropdownMenuItem>
                              <DropdownMenuItem onClick={() => handleDownload(file)}>
                                <Download className="mr-2 h-3.5 w-3.5" /> Download
                              </DropdownMenuItem>
                            </DropdownMenuContent>
                          </DropdownMenu>
                        </td>
                      </tr>
                    ))
                  )}
                </tbody>
              </table>
            </div>

            {/* Pagination */}
            {!isLoading && totalEntries > 0 && (
              <div className="border-t border-gray-200 bg-gray-50 px-6 py-4">
                <div className="flex flex-col md:flex-row items-center justify-between gap-4">
                  <div className="text-sm text-gray-600">
                    Page <span className="font-semibold text-gray-900">{page}</span> of{" "}
                    <span className="font-semibold text-gray-900">{totalPages}</span>
                  </div>
                  <div className="flex items-center space-x-2">
                    <Button variant="outline" size="sm" onClick={() => setPage(1)} disabled={page === 1} className="border-gray-300">
                      <ChevronsLeft className="h-4 w-4" />
                    </Button>
                    <Button variant="outline" size="sm" onClick={() => setPage(Math.max(1, page - 1))} disabled={page === 1} className="border-gray-300">
                      <ChevronLeft className="h-4 w-4" />
                    </Button>
                    <div className="flex items-center space-x-1 mx-2">
                      {Array.from({ length: Math.min(5, totalPages) }, (_, i) => {
                        let pageNum;
                        if (totalPages <= 5) pageNum = i + 1;
                        else if (page <= 3) pageNum = i + 1;
                        else if (page >= totalPages - 2) pageNum = totalPages - 4 + i;
                        else pageNum = page - 2 + i;
                        return (
                          <Button
                            key={pageNum}
                            variant={page === pageNum ? "default" : "outline"}
                            size="sm"
                            onClick={() => setPage(pageNum)}
                            className={
                              page === pageNum
                                ? "bg-[#1E1B4B] hover:bg-[#2A2675]"
                                : "border-gray-300 hover:bg-gray-100"
                            }
                          >
                            {pageNum}
                          </Button>
                        );
                      })}
                    </div>
                    <Button variant="outline" size="sm" onClick={() => setPage(Math.min(totalPages, page + 1))} disabled={page === totalPages} className="border-gray-300">
                      <ChevronRight className="h-4 w-4" />
                    </Button>
                    <Button variant="outline" size="sm" onClick={() => setPage(totalPages)} disabled={page === totalPages} className="border-gray-300">
                      <ChevronsRight className="h-4 w-4" />
                    </Button>
                  </div>
                  <div className="text-sm text-gray-600">
                    <span className="font-semibold">{showingFrom}</span> – <span className="font-semibold">{showingTo}</span> of{" "}
                    <span className="font-semibold">{totalEntries}</span> entries
                  </div>
                </div>
              </div>
            )}
          </div>
        </CardContent>
      </Card>

      {/* View Details Modal */}
      <Dialog open={!!detailId} onOpenChange={() => setDetailId(null)}>
        <DialogContent className="sm:max-w-md">
          <DialogHeader>
            <DialogTitle>Bank File Details</DialogTitle>
            <DialogDescription>
              {detailData?.filename ?? "Loading..."}
            </DialogDescription>
          </DialogHeader>
          {isLoadingDetail ? (
            <div className="flex justify-center py-4">
              <Loader2 className="h-6 w-6 animate-spin" />
            </div>
          ) : detailData ? (
            <div className="space-y-3">
              <div className="grid grid-cols-2 gap-3 text-sm">
                <div>
                  <p className="text-xs font-semibold uppercase text-gray-400">Format</p>
                  <p className="font-medium text-gray-900 uppercase">{detailData.file_format}</p>
                </div>
                <div>
                  <p className="text-xs font-semibold uppercase text-gray-400">Total Amount</p>
                  <p className="font-medium text-gray-900">{formatPKR(detailData.total_amount)}</p>
                </div>
                <div>
                  <p className="text-xs font-semibold uppercase text-gray-400">Transactions</p>
                  <p className="font-medium text-gray-900">{detailData.transaction_count}</p>
                </div>
              </div>
            </div>
          ) : (
            <div className="text-center text-sm text-gray-500">No details available.</div>
          )}
          <DialogFooter>
            <Button variant="outline" onClick={() => setDetailId(null)}>
              Close
            </Button>
            {detailId && (
              <Button
                onClick={async () => {
                  try {
                    const blob = await downloadBankFile(detailId);
                    const url = window.URL.createObjectURL(blob);
                    const link = document.createElement("a");
                    link.href = url;
                    link.download = detailData?.filename ?? "bank-file.csv";
                    document.body.appendChild(link);
                    link.click();
                    link.remove();
                    window.URL.revokeObjectURL(url);
                    toast.success("Download started.");
                  } catch (err) {
                    showApiError(err, { fallbackMessage: "Download failed." });
                  }
                }}
                className="bg-[#1E1B4B] hover:bg-[#2A2675] text-white"
              >
                <Download className="mr-2 h-4 w-4" /> Download
              </Button>
            )}
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </div>
  );
}